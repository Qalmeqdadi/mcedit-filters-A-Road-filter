"use client";

import { useEffect, useState } from "react";

import { API_URL } from "@/lib/api";
import { formatGst } from "@/lib/format";
import { statusColor } from "@/lib/risk";
import { usePulse } from "@/lib/usePulse";

import { CommodityTable } from "./CommodityTable";
import { DepletionChart } from "./DepletionChart";
import { EventStream } from "./EventStream";
import { KpiStrip } from "./KpiStrip";
import { ThreatPanel } from "./ThreatPanel";
import { UaeMap } from "./UaeMap";

function Clock() {
  const [now, setNow] = useState<Date | null>(null);
  useEffect(() => {
    setNow(new Date());
    const t = setInterval(() => setNow(new Date()), 1000);
    return () => clearInterval(t);
  }, []);
  return <span className="clock">{now ? `${formatGst(now)} GST` : "--:--:-- GST"}</span>;
}

export function GlobalPulse() {
  const { pulse, events, error, stream, busy, triggerDisruption, reset } = usePulse();
  const state = pulse?.state;
  const topThreat = state?.threats[0];

  return (
    <div className="shell">
      <header className="topbar">
        <div className="brand">
          <span className="brand-mark" aria-hidden />
          <div>
            <div className="brand-name">
              HAYAT <span className="brand-sep">|</span> <span lang="ar">حياة</span>
            </div>
            <div className="brand-tag">Autonomous Resilience Intelligence</div>
          </div>
        </div>
        <div className="screen-title">
          <span>GLOBAL PULSE</span>
          <small>UAE food &amp; logistics · synthetic data</small>
        </div>
        <div className="topbar-right">
          <Clock />
          {state && (
            <span className="calc-time" title={`Run ${state.run_id}`}>
              recalculated {formatGst(state.computed_at)}
            </span>
          )}
          {state && state.kpis.active_signals > 0 && (
            <button className="btn btn-ghost" onClick={reset} disabled={busy !== null}>
              {busy === "reset" ? "Resetting…" : "Reset to baseline"}
            </button>
          )}
          <button
            className="btn btn-primary"
            onClick={triggerDisruption}
            disabled={busy !== null || !pulse}
          >
            {busy === "trigger" ? "Processing event…" : "Trigger Demo Disruption"}
          </button>
        </div>
      </header>

      {error && (
        <div className="banner banner-error" role="alert">
          <strong>API unavailable.</strong> {error}. Expected the HAYAT API at <code>{API_URL}</code>
          . Start it and seed the database (see README).
        </div>
      )}

      {topThreat && (
        <div
          className="banner banner-threat"
          role="alert"
          style={{ borderColor: statusColor(topThreat.risk_level) }}
        >
          <span className="banner-dot" style={{ background: statusColor(topThreat.risk_level) }} />
          <strong>{topThreat.risk_level} THREAT</strong>
          <span>{topThreat.headline}</span>
          {state.threats.length > 1 && (
            <span className="banner-more">+{state.threats.length - 1} more</span>
          )}
        </div>
      )}

      {!state ? (
        <div className="loading">{error ? "Waiting for the API…" : "Loading resilience state…"}</div>
      ) : (
        <main className="grid">
          <KpiStrip state={state} />
          <div className="col">
            <section className="panel" aria-label="UAE operating picture">
              <header className="panel-head">
                <h2>UAE Operating Picture</h2>
                <span className="panel-meta">
                  {pulse.network.ports.length} ports · {pulse.network.warehouses.length} warehouses
                  · {pulse.network.hospitals.length} hospitals · {pulse.network.zones.length} zones
                </span>
              </header>
              <UaeMap network={pulse.network} status={state.network_status} />
            </section>
            <DepletionChart commodities={state.commodities} horizon={state.horizon_days} />
          </div>
          <div className="col">
            <ThreatPanel state={state} network={pulse.network} />
            <EventStream events={events} status={stream} />
          </div>
          <CommodityTable commodities={state.commodities} />
        </main>
      )}

      <footer className="foot">
        All values are calculated by deterministic code from synthetic data. No figure on this
        screen is generated by a language model.
      </footer>
    </div>
  );
}
