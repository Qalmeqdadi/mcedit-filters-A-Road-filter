// Open-data connector (build time): downloads Jordan series from open mirrors and writes
// src/data/openData.generated.ts with provenance (URL, licence, fetch time, row counts).
//
//   node scripts/fetch-open-data.mjs
//
// Sources are mirrors of World Bank WDI (github.com/datasets, ODC-PDDL) and Our World in Data's
// energy dataset (github.com/owid/energy-data, CC BY 4.0). They are reachable from this build
// environment; the page can also refresh them at runtime where the browser allows it.
import { writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

export const OPEN_SOURCES = [
  { id: "OPEN_WB_GDP", url: "https://raw.githubusercontent.com/datasets/gdp/main/data/gdp.csv", licence: "ODC-PDDL-1.0 (World Bank WDI NY.GDP.MKTP.CD mirror)" },
  { id: "OPEN_WB_POP", url: "https://raw.githubusercontent.com/datasets/population/main/data/population.csv", licence: "ODC-PDDL-1.0 (World Bank WDI SP.POP.TOTL mirror)" },
  { id: "OPEN_WB_CPI", url: "https://raw.githubusercontent.com/datasets/inflation/main/data/inflation-consumer.csv", licence: "ODC-PDDL-1.0 (World Bank WDI FP.CPI.TOTL.ZG mirror)" },
  { id: "OPEN_OWID_ENERGY", url: "https://raw.githubusercontent.com/owid/energy-data/master/owid-energy-data.csv", licence: "CC BY 4.0 (Our World in Data, based on Ember and the Energy Institute)" },
];

function parseCsv(text) {
  const lines = text.split(/\r?\n/).filter(Boolean);
  const split = (l) => {
    const out = [];
    let cur = "", q = false;
    for (let i = 0; i < l.length; i++) {
      const c = l[i];
      if (q) { if (c === '"' && l[i + 1] === '"') { cur += '"'; i++; } else if (c === '"') q = false; else cur += c; }
      else if (c === '"') q = true; else if (c === ",") { out.push(cur); cur = ""; } else cur += c;
    }
    out.push(cur);
    return out;
  };
  const head = split(lines[0]);
  return lines.slice(1).map((l) => Object.fromEntries(split(l).map((v, i) => [head[i], v])));
}

const num = (v) => (v === "" || v === undefined ? null : Number(v));

async function get(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url} → HTTP ${r.status}`);
  return r.text();
}

const out = { fetchedAt: new Date().toISOString(), sources: [], gdpUsd: [], population: [], inflation: [], electricity: [] };
for (const s of OPEN_SOURCES) {
  const text = await get(s.url);
  const rows = parseCsv(text);
  let picked = [];
  if (s.id === "OPEN_WB_GDP") picked = out.gdpUsd = rows.filter((r) => r["Country Code"] === "JOR").map((r) => ({ year: +r.Year, value: +r.Value }));
  if (s.id === "OPEN_WB_POP") picked = out.population = rows.filter((r) => r["Country Code"] === "JOR").map((r) => ({ year: +r.Year, value: +r.Value }));
  if (s.id === "OPEN_WB_CPI") picked = out.inflation = rows.filter((r) => r["Country Code"] === "JOR").map((r) => ({ year: +r.Year, value: +r.Inflation }));
  if (s.id === "OPEN_OWID_ENERGY") picked = out.electricity = rows.filter((r) => r.country === "Jordan" && +r.year >= 2000 && r.electricity_demand !== "").map((r) => ({ year: +r.year, demandTWh: num(r.electricity_demand), generationTWh: num(r.electricity_generation), renewablesShare: num(r.renewables_share_elec), solarShare: num(r.solar_share_elec), perCapitaKWh: num(r.per_capita_electricity), netImportsTWh: num(r.net_elec_imports), ghgMt: num(r.greenhouse_gas_emissions) }));
  picked.sort((a, b) => a.year - b.year);
  out.sources.push({ id: s.id, url: s.url, licence: s.licence, rows: picked.length, firstYear: picked[0]?.year ?? null, lastYear: picked.at(-1)?.year ?? null, sha256: createHash("sha256").update(text).digest("hex").slice(0, 16) });
  console.log(`${s.id}: ${picked.length} Jordan rows (${picked[0]?.year}–${picked.at(-1)?.year})`);
}

writeFileSync(
  new URL("../src/data/openData.generated.ts", import.meta.url),
  `// Generated by scripts/fetch-open-data.mjs — do not edit by hand.\n// Jordan series from open mirrors of World Bank WDI and Our World in Data (see sources[]).\nimport type { OpenData } from "./openData";\n\nexport const OPEN_DATA_SNAPSHOT: OpenData = ${JSON.stringify(out, null, 1)};\n`,
);
console.log("wrote src/data/openData.generated.ts");
